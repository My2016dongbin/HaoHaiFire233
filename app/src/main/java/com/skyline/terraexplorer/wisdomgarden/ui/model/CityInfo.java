public class CityInfo {
    public String countyName;
    public String countyPopulation;
    public String builtArea;
    public String cityGreenArea;
    public String cityParkGreenArea;

    public String getCountyName() {
        return countyName;
    }

    public void setCountyName(String countyName) {
        this.countyName = countyName;
    }

    public String getCountyPopulation() {
        return countyPopulation;
    }

    public void setCountyPopulation(String countyPopulation) {
        this.countyPopulation = countyPopulation;
    }

    public String getBuiltArea() {
        return builtArea;
    }

    public void setBuiltArea(String builtArea) {
        this.builtArea = builtArea;
    }

    public String getCityGreenArea() {
        return cityGreenArea;
    }

    public void setCityGreenArea(String cityGreenArea) {
        this.cityGreenArea = cityGreenArea;
    }

    public String getCityParkGreenArea() {
        return cityParkGreenArea;
    }

    public void setCityParkGreenArea(String cityParkGreenArea) {
        this.cityParkGreenArea = cityParkGreenArea;
    }
}
